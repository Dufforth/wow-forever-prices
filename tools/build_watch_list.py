#!/usr/bin/env python3
"""Pick the crafted gear people trade most, for the addon's light scan.

    python tools/build_watch_list.py <price data folder> addon/DufforthAHScanner/Watch.lua

The light scan already covers materials, consumables and rare or epic gear, so this
list is the uncommon crafted gear with the most bought (estimated) and posted across
Blizzard's markets.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIMIT = 15
WEAPON, ARMOR, UNCOMMON = 2, 4, 2


def pick(catalog, houses, limit=LIMIT):
    crafted = {recipe["i"] for recipe in catalog["recipes"]}
    scores = {}
    for items in houses:
        for key, row in items.items():
            item = catalog["items"].get(key)
            if not item or int(key) not in crafted or item["cl"] not in (WEAPON, ARMOR) or item["q"] != UNCOMMON:
                continue
            bought = row[6] if len(row) > 6 else 0
            scores[int(key)] = scores.get(int(key), 0) + bought * 10 + (row[2] or 0)
    return [item for item, score in sorted(scores.items(), key=lambda pair: (-pair[1], pair[0])) if score > 0][:limit]


def main(data, out):
    catalog = json.loads((ROOT / "site/catalog.json").read_text(encoding="utf-8"))
    meta = json.loads((Path(data) / "meta.json").read_text(encoding="utf-8"))
    houses = [json.loads((Path(data) / f"h{h['id']}.json").read_text(encoding="utf-8"))["items"]
              for h in meta["houses"] if h.get("source") == "blizzard"]
    ids = pick(catalog, houses)
    Path(out).write_text("-- Generated by tools/build_watch_list.py. Popular crafted gear for the light scan.\n"
                         f"DufforthAHScannerWatch = {{ {', '.join(map(str, ids))} }}\n", encoding="utf-8")
    return ids


if __name__ == "__main__":
    print(main(sys.argv[1], sys.argv[2]))
