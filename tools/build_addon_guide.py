#!/usr/bin/env python3
"""Write the addon's GuideData.lua from catalog/route.json: the leveling routes, every Horde quest
(title, levels, chain, giver and turn-in places, objectives) and the map IDs for map pins.

    python tools/build_addon_guide.py addon/DufforthTweaksHelper/GuideData.lua
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def value(v):
    """A Lua literal for JSON-like data (lists become arrays, dicts keyed tables)."""
    if v is None:
        return "nil"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'
    if isinstance(v, float):
        return f"{v:g}"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, list):
        return "{" + ",".join(value(x) for x in v) + "}"
    if isinstance(v, dict):
        return "{" + ",".join(f"[{value(k)}]={value(x)}" for k, x in v.items()) + "}"
    raise TypeError(type(v))


def slim(step, quests):
    """The step without the text the addon doesn't read: pick-ups, hand-ins and objectives are written from the quest
    data (18 routes made the file too big with it)."""
    step = list(step)
    if step[0] in ("accept", "turnin", "do") and step[1] in quests and (step[0] != "do" or step[7]):
        step[6] = ""
    while len(step) > 8 and step[-1] in (None, ""):
        step.pop()
    return step


def lua(data):
    quests = {int(k): v for k, v in data["quests"].items()}
    extras = dict(data["extras"])
    extras["dungeonOf"] = {int(k): v for k, v in extras.get("dungeonOf", {}).items()}  # looked up by quest ID
    lines = [
        "-- Generated by tools/build_addon_guide.py from catalog/route.json (catalog/build_route.py). Classic estimates.",
        "-- Forever's own quests are placed with data from RestedXP Guides (https://github.com/RestedXP/RXPGuides), CC BY-NC-SA 4.0;",
        "-- this file is shared under CC BY-NC-SA 4.0 too (see LICENSE-DATA.md in the project).",
        "-- routes[start] = { races = {...}, steps = { {kind, quest, zone, x, y, level, text} } }",
        "-- quests[id] = {title, level, minLevel, classes, type, prev, nextInChain, giver, {zone, x, y}, turnIn, {zone, x, y},",
        "--               goals {{kind, name, count, zone, x, y}}, gear rewards, start item, races}",
        "DufforthTweaksHelperGuideData = {",
        "  uiMaps = " + value(data["uiMaps"]) + ",",
        "  extras = " + value(extras) + ",",
        "  -- travel = { flights = {{name, zone, x, y, continent}}, continents = {zone = 0|1}, transports = {{kind, from, to}} }",
        "  travel = " + value(data.get("travel", {})) + ",",
        "  -- guides = { {name, note} }: questline guides, each with its own route below",
        "  guides = " + value(data.get("guides", [])) + ",",
        "  routes = {",
    ]
    for start, route in data["routes"].items():
        lines.append(f"    [{value(start)}] = {{ races = {value(route['races'])}, steps = {{")
        lines += ["      " + value(slim(step, quests)) + "," for step in route["steps"]]
        lines.append("    } },")
    lines.append("  },")
    lines.append("  quests = {")
    lines += [f"    [{qid}] = {value(q)}," for qid, q in sorted(quests.items())]
    lines.append("  },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(out):
    data = json.loads((ROOT / "catalog" / "route.json").read_text(encoding="utf-8"))
    text = lua(data)
    Path(out).write_text(text, encoding="utf-8")
    print(f"{out}: {len(data['quests'])} quests, {sum(len(r['steps']) for r in data['routes'].values())} steps, {len(text) // 1024} KB")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
