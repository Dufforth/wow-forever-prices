#!/usr/bin/env python3
"""Write the addon's ConsumablesData.lua: every buyable food buff, elixir, flask, scroll and potion
with what it does (catalog/consumables.json) and its vendor price when a vendor sells it.

    python tools/build_addon_consumables.py addon/DufforthTweaksHelper/ConsumablesData.lua
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_addon_crafts  # noqa: E402

lua_string = build_addon_crafts.lua_string


def load():
    return json.loads((ROOT / "catalog" / "consumables.json").read_text(encoding="utf-8"))


def consumable_ids():
    """Items whose auction prices the Class tab needs (build_addon_prices.wanted_ids)."""
    return {int(i) for i in load()["items"]}


def rows(data, catalog):
    out = []
    for item_id, (kind, seconds, effects, *rest) in sorted(data["items"].items(), key=lambda kv: int(kv[0])):
        item = catalog["items"].get(item_id)
        if not item:
            continue
        vendor = int(item.get("buy") or 0) if item.get("v") else 0
        body = ", ".join(f"{k} = {v}" for k, v in sorted(effects.items()))
        weapons = rest[0] if rest else 0
        out.append(f'{{{item_id},{lua_string(item["n"])},"{kind}",{item.get("rl", 0)},{seconds},{vendor},{{ {body} }},{weapons}}},')
    return out


def lua(data, catalog):
    lines = ["-- Generated by tools/build_addon_consumables.py from the game's spell tables (catalog/build_consumables.py).",
             "-- {item, name, kind, required level, seconds the buff lasts, vendor price (0 = not sold), effects,",
             "--  weapon types a stone or oil can go on (bit per weapon subclass, 0 = any)}",
             "DufforthTweaksHelperConsumableData = {"]
    lines += rows(data, catalog)
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(out):
    data, catalog = load(), build_addon_crafts.load_catalog()
    text = lua(data, catalog)
    Path(out).write_text(text, encoding="utf-8")
    print(f"{out}: {text.count(chr(10)) - 5} consumables, {len(text) // 1024} KB")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
