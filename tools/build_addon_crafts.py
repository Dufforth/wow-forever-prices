#!/usr/bin/env python3
"""Recipes for the addon's Crafting tab, from the page's game data (site/catalog.json).

    python tools/build_addon_crafts.py addon/DufforthTweaksHelper/Crafts.lua

Writes every recipe that makes gear you can disenchant, the recipes for crafted materials
(bolts, bars, leather) so their cost can be worked out, and what vendors charge for the
materials they sell. Prices themselves come from Prices.lua.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROFESSIONS = ["Alchemy", "Blacksmithing", "Cooking", "Enchanting", "Engineering", "First Aid", "Leatherworking", "Mining", "Tailoring"]
WEAPON, ARMOR = 2, 4
SKIP_SLOTS = {4, 19}  # shirts and tabards never disenchant
TRAINER, OTHER = 0, -1


def load_catalog():
    return json.loads((ROOT / "site" / "catalog.json").read_text(encoding="utf-8"))


def disenchantable(item, no_de):
    return (item and item.get("q", 0) >= 2 and item.get("cl") in (WEAPON, ARMOR) and item.get("il", 0) > 0
            and not item.get("nd") and item.get("inv") not in SKIP_SLOTS)


def learn_code(recipe):
    """Positive: the recipe item that teaches it. 0: a trainer. -1: another way or not known."""
    if recipe.get("ri"):
        return int(recipe["ri"])
    return TRAINER if "trainer" in (recipe.get("o") or []) else OTHER


def gear_recipes(catalog):
    items, no_de = catalog["items"], set(catalog.get("noDisenchant", []))
    out = []
    for recipe in catalog["recipes"]:
        product = items.get(str(recipe["i"]))
        if recipe["p"] in PROFESSIONS and recipe["i"] not in no_de and disenchantable(product, no_de) and recipe["r"]:
            out.append(recipe)
    return sorted(out, key=lambda r: (r["p"], r.get("sk") or 999, r["s"]))


def is_vendor(items, item_id):
    item = items.get(str(item_id)) or {}
    return bool(item.get("v") and item.get("buy", 0) > 0)


def material_recipes(catalog, recipes):
    """One recipe for each crafted material the gear needs (and what those need), vendors excluded."""
    items = catalog["items"]
    by_item = {}
    for recipe in catalog["recipes"]:
        by_item.setdefault(recipe["i"], []).append(recipe)
    chosen, todo = {}, [rid for r in recipes for rid, _ in r["r"]]
    while todo:
        item_id = todo.pop()
        if item_id in chosen or is_vendor(items, item_id) or item_id not in by_item:
            continue
        recipe = min(by_item[item_id], key=lambda r: (len(r["r"]), r["s"]))
        chosen[item_id] = recipe
        todo.extend(rid for rid, _ in recipe["r"])
    return chosen


def reagent_ids(catalog):
    """Every material any listed recipe uses, so Prices.lua carries their prices."""
    recipes = gear_recipes(catalog)
    ids = {rid for r in recipes for rid, _ in r["r"]}
    for recipe in material_recipes(catalog, recipes).values():
        ids.update(rid for rid, _ in recipe["r"])
    return sorted(ids), sorted(r["i"] for r in recipes)


def lua_string(text):
    return '"' + str(text).replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def flat(reagents):
    return "{ " + ", ".join(f"{rid}, {count}" for rid, count in reagents) + " }"


def lua(catalog):
    items = catalog["items"]
    recipes = gear_recipes(catalog)
    materials = material_recipes(catalog, recipes)
    used = {rid for r in recipes for rid, _ in r["r"]} | {rid for r in materials.values() for rid, _ in r["r"]}
    vendor = {rid: int(round(items[str(rid)]["buy"])) for rid in sorted(used) if is_vendor(items, rid)}
    lines = [
        "-- Generated by tools/build_addon_crafts.py from the Forever Prices page's game data.",
        "-- Professions, by number in the rows below.",
        "DufforthTweaksHelperProfessions = { " + ", ".join(lua_string(p) for p in PROFESSIONS) + " }",
        "-- What a vendor charges for a material, in copper. A vendor price always wins over the auction house.",
        "DufforthTweaksHelperVendor = { " + ", ".join(f"[{k}]={v}" for k, v in vendor.items()) + " }",
        "-- Crafted materials: [material] = { how many one craft makes, { material, count, ... } }",
        "DufforthTweaksHelperMaterialCrafts = {",
    ]
    for item_id in sorted(materials):
        recipe = materials[item_id]
        lines.append(f"  [{item_id}] = {{ {recipe['c'] or 1}, {flat(recipe['r'])} }},")
    lines += [
        "}",
        "-- Gear you can craft and disenchant: { spell, profession, skill (0 = not known), item, how many,",
        "--   quality, item level, class (2 weapon, 4 armor), how to learn (recipe item, 0 trainer, -1 other), name, materials }",
        "DufforthTweaksHelperCrafts = {",
    ]
    for r in recipes:
        product = items[str(r["i"])]
        lines.append(f"  {{ {r['s']}, {PROFESSIONS.index(r['p']) + 1}, {r.get('sk') or 0}, {r['i']}, {r['c'] or 1}, "
                     f"{product['q']}, {product['il']}, {product['cl']}, {learn_code(r)}, {lua_string(product['n'])}, {flat(r['r'])} }},")
    lines.append("}")
    return "\n".join(lines) + "\n", len(recipes), len(materials), len(vendor)


def main(out):
    text, gear, materials, vendor = lua(load_catalog())
    Path(out).write_text(text, encoding="utf-8")
    return gear, materials, vendor


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    print("addon crafts: %d gear recipes, %d material recipes, %d vendor materials" % main(sys.argv[1]))
