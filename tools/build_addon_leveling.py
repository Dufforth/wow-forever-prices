#!/usr/bin/env python3
"""Write the addon's LevelingData.lua: every profession recipe with its skill colors, materials
and how to learn it, plus the trainers and recipe vendors (catalog/leveling_sources.json).

    python tools/build_addon_leveling.py addon/DufforthTweaksHelper/LevelingData.lua
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_addon_crafts  # noqa: E402

PROFESSIONS = build_addon_crafts.PROFESSIONS
lua_string = build_addon_crafts.lua_string
STARTER_SKILL = 1  # trainer recipes at skill 1 come with the profession


def load_sources():
    return json.loads((ROOT / "catalog" / "leveling_sources.json").read_text(encoding="utf-8"))


def how_to_learn(recipe, sources):
    """t: trainer, s: comes with the profession, v: recipe sold by a vendor, i: recipe item
    (drop, quest...), ?: not known."""
    spell, item = str(recipe["s"]), recipe.get("ri")
    if spell in sources["trainers"]:
        return "t"
    if item and str(item) in sources["vendors"]:
        return "v"
    if item:
        return "i"
    if "trainer" in recipe["o"] and recipe["sk"] <= STARTER_SKILL:
        return "s"
    if "trainer" in recipe["o"]:
        return "t"
    return "?"


def recipe_rows(catalog, sources):
    """{spell, prof, learn, yellow, gray, product, count, sell, name, how, recipe item, materials}"""
    rows = []
    for r in catalog["recipes"]:
        if r["p"] not in PROFESSIONS:
            continue
        gray = sources["gray"].get(str(r["s"])) or 0
        yellow = r.get("y") or 0
        if gray <= 0:
            continue  # gives no skill
        learn = max(1, r["sk"] or 1)
        yellow = max(yellow, learn)
        gray = max(gray, yellow)
        product = catalog["items"].get(str(r["i"]), {})
        rows.append({"spell": r["s"], "prof": PROFESSIONS.index(r["p"]) + 1, "learn": learn, "yellow": yellow, "gray": gray,
                     "product": r["i"], "count": r.get("c") or 1, "sell": int(product.get("sell") or 0), "name": r["n"],
                     "how": how_to_learn(r, sources), "ri": r.get("ri") or 0, "mats": r["r"]})
    rows.sort(key=lambda row: (row["prof"], row["learn"], row["spell"]))
    return rows


def leveling_ids(catalog=None, sources=None):
    """Items the Leveling tab wants auction prices for: materials, products and recipe items."""
    catalog = catalog or build_addon_crafts.load_catalog()
    sources = sources or load_sources()
    ids = set()
    for row in recipe_rows(catalog, sources):
        ids.add(row["product"])
        if row["ri"]:
            ids.add(row["ri"])
        ids.update(m[0] for m in row["mats"])
    return ids


def lua(catalog, sources):
    out = ["-- Generated by tools/build_addon_leveling.py from the Forever Prices page's game data.",
           "-- Recipes: {spell, profession, learn skill, yellow, gray, product, count, product vendor price,",
           "--   name, how to learn (t trainer, s with the profession, v vendor recipe, i recipe item, ? unknown),",
           "--   recipe item, {material, count, ...}}. Trainers and vendors: Classic estimates (CMaNGOS).",
           "DufforthTweaksHelperLevelRecipes = {"]
    for row in recipe_rows(catalog, sources):
        mats = ",".join(f"{m},{c}" for m, c in row["mats"])
        out.append(f'{{{row["spell"]},{row["prof"]},{row["learn"]},{row["yellow"]},{row["gray"]},{row["product"]},{row["count"]},'
                   f'{row["sell"]},{lua_string(row["name"])},"{row["how"]}",{row["ri"]},{{{mats}}}}},')
    out.append("}")
    out.append("-- {name, title, side (A, H or both), zone, x, y}")
    out.append("DufforthTweaksHelperLevelNPCs = {")
    for name, title, side, zone, x, y in sources["npcs"]:
        out.append(f'{{{lua_string(name)},{lua_string(title)},"{side}",{lua_string(zone or "")},{x if x is not None else "nil"},{y if y is not None else "nil"}}},')
    out.append("}")
    out.append("-- [recipe spell] = {npc, training cost, skill needed, ...}")
    out.append("DufforthTweaksHelperLevelTrainers = {")
    for spell, rows in sources["trainers"].items():
        out.append(f"[{spell}]={{" + ",".join(f"{npc + 1},{cost},{skill}" for npc, cost, skill in rows) + "},")
    out.append("}")
    out.append("-- [recipe item] = {npc, price, limited supply (1/0), ...}")
    out.append("DufforthTweaksHelperLevelVendors = {")
    for item, rows in sources["vendors"].items():
        out.append(f"[{item}]={{" + ",".join(f"{npc + 1},{price},{limited}" for npc, price, limited in rows) + "},")
    out.append("}")
    return "\n".join(out) + "\n"


def main(path):
    catalog, sources = build_addon_crafts.load_catalog(), load_sources()
    text = lua(catalog, sources)
    Path(path).write_text(text, encoding="utf-8", newline="\n")
    print(f"{path}: {len(recipe_rows(catalog, sources))} recipes, {len(sources['trainers'])} trained, "
          f"{len(sources['vendors'])} recipe items sold, {len(text) // 1024} KB")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(ROOT / "addon" / "DufforthTweaksHelper" / "LevelingData.lua"))
