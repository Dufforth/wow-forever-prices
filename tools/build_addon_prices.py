#!/usr/bin/env python3
"""Auction prices bundled with the addon, for its disenchant tooltips and window.

    python tools/build_addon_prices.py <price data folder> addon/DufforthTweaksHelper/Prices.lua

Addons can't reach the internet, so each download carries Blizzard's prices from the
time it was built: every enchanting material, and the tradable weapons and armor that
can be disenchanted (to tell when gear sells for more than its materials), and the
materials of every recipe that makes such gear, for the Crafting tab.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# Every dust, essence, shard and crystal the disenchant tables can give.
MATERIALS = [10940, 10938, 10939, 10998, 11082, 11134, 11135, 11174, 11175, 16202, 16203, 11083,
             11137, 11176, 16204, 10978, 11084, 11138, 11139, 11177, 11178, 14343, 14344, 20725]


def wanted_ids():
    """Enchanting materials, disenchantable gear, every crafting material and product the
    Crafting tab needs (build_addon_crafts.py), and the Leveling tab's materials, products and
    recipe items (build_addon_leveling.py), and the class tab's consumables (build_addon_consumables.py)."""
    import build_addon_crafts
    gear = json.loads((ROOT / "site" / "gear.json").read_text(encoding="utf-8"))
    import build_addon_leveling
    catalog = build_addon_crafts.load_catalog()
    reagents, products = build_addon_crafts.reagent_ids(catalog)
    leveling = build_addon_leveling.leveling_ids(catalog)
    import build_addon_consumables
    consumables = build_addon_consumables.consumable_ids()
    import build_addon_zones
    zone_items = build_addon_zones.zone_item_ids()
    return sorted(set(MATERIALS) | {int(key) for key in gear} | set(reagents) | set(products) | leveling | consumables | zone_items)


def prices_for(items, ids):
    """Market price (or lowest) for each wanted item that is listed."""
    out = {}
    for item in ids:
        row = items.get(str(item))
        if row and row[2] and row[2] > 0:
            price = row[1] if row[1] is not None else row[0]
            if price:
                out[item] = int(price)
    return out


def lua(houses, stamp, no_disenchant=()):
    lines = ["-- Generated by tools/build_addon_prices.py. Blizzard auction prices at download time.",
             "-- Gear the game never disenchants (Enchanting-made wands, some sets), from its item flags.",
             "DufforthTweaksHelperNoDE = { " + ", ".join(f"[{i}]=true" for i in sorted(no_disenchant)) + " }",
             f"DufforthTweaksHelperPrices = {{ at = {int(stamp)},"]
    for market in sorted(houses):
        prices = houses[market]
        if prices:
            body = ", ".join(f"[{k}]={v}" for k, v in sorted(prices.items()))
            lines.append(f'  ["{market}"] = {{ {body} }},')
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(data, out):
    meta = json.loads((Path(data) / "meta.json").read_text(encoding="utf-8"))
    ids = wanted_ids()
    houses, stamp = {}, 0
    for house in meta["houses"]:
        path = Path(data) / f"h{house['id']}.json"
        if not path.exists():
            continue
        file = json.loads(path.read_text(encoding="utf-8"))
        houses[house["id"]] = prices_for(file.get("items", {}), ids)
        stamp = max(stamp, file.get("ts") or 0)
    catalog = json.loads((ROOT / "site" / "catalog.json").read_text(encoding="utf-8"))
    Path(out).write_text(lua(houses, stamp, catalog.get("noDisenchant", [])), encoding="utf-8")
    return houses


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    found = main(sys.argv[1], sys.argv[2])
    print(f"addon prices: {sum(len(p) for p in found.values())} across {sum(1 for p in found.values() if p)} markets")
