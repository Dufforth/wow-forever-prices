#!/usr/bin/env python3
"""Write the addon's GrindData.lua from catalog/grind.json (catalog/build_grind.py): places to kill
monsters for experience and gold. Experience, kills per hour and gold per hour are worked out in
the game (Grind.lua) from your level, class and spec and the bundled auction prices.

    python tools/build_addon_grind.py addon/DufforthTweaksHelper/GrindData.lua
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_addon_crafts  # noqa: E402
import build_addon_zones  # noqa: E402

S = build_addon_crafts.lua_string
value = build_addon_zones.value


def load():
    return json.loads((ROOT / "catalog" / "grind.json").read_text(encoding="utf-8"))


def grind_item_ids():
    """Drops whose auction prices the Grind tab needs (build_addon_prices.wanted_ids)."""
    return {int(i) for i in load()["items"]}


def lua(data):
    zones = sorted({s[0] for s in data["spots"]})
    index = {z: i + 1 for i, z in enumerate(zones)}
    lines = ["-- Generated by tools/build_addon_grind.py (catalog/build_grind.py): Classic estimates from CMaNGOS.",
             "-- spot: {zone (index in DufforthTweaksHelperGrindZones), x, y, minLevel, maxLevel, spawns, gap yards,",
             "--        respawn seconds, flags (1 caster, 2 healer, 4 flees, 8 elite, 16 pack), vendor copper per kill,",
             "--        {monsters}, {{item, expected per kill}}}",
             "DufforthTweaksHelperGrindZones = " + value(zones),
             "DufforthTweaksHelperGrindSpots = {"]
    for s in data["spots"]:
        lines.append(value([index[s[0]]] + s[1:]) + ",")
    lines.append("}")
    lines.append("-- mob: {name, minLevel, maxLevel, model id, creature type, family, flags, vendor copper per kill, {{item, per kill}}}")
    lines.append("DufforthTweaksHelperGrindMobs = {")
    for m in data.get("mobs", []):
        lines.append(value(m) + ",")
    lines.append("}")
    lines.append("-- item: {name, quality, vendor sell price}")
    lines.append("DufforthTweaksHelperGrindItems = {" + ",".join(f"[{i}]={value(v)}" for i, v in sorted(data["items"].items(), key=lambda kv: int(kv[0]))) + "}")
    tune = ROOT / "catalog" / "grind_tune.json"
    if tune.exists():
        import tune_grind
        lines.append(tune_grind.tune_lua(json.loads(tune.read_text(encoding="utf-8"))))
    return "\n".join(lines) + "\n"


def main(out):
    Path(out).write_text(lua(load()), encoding="utf-8")
    print(f"{out}: {Path(out).stat().st_size // 1024} KB")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
