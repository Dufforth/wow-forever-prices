#!/usr/bin/env python3
"""Write the addon's ZoneData.lua from catalog/zone_guide.json: per zone, the quests, the quests
started by a dropped item, the rare monsters and the monsters worth farming. It also carries what
each class trainer teaches (catalog/class_trainers.json), for the "new spells to train" reminder:
kept in this file so the reminder needed no new file (new files need a full game restart).

    python tools/build_addon_zones.py addon/DufforthTweaksHelper/ZoneData.lua
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_addon_crafts  # noqa: E402

S = build_addon_crafts.lua_string


def load():
    return json.loads((ROOT / "catalog" / "zone_guide.json").read_text(encoding="utf-8"))


def zone_item_ids():
    """Items whose auction prices the Zone tab needs (build_addon_prices.wanted_ids)."""
    return {int(i) for i in load()["items"]}


def value(v):
    if v is None:
        return "nil"
    if isinstance(v, str):
        return S(v)
    if isinstance(v, list):
        return "{" + ",".join(value(x) for x in v) + "}"
    if isinstance(v, float):
        return f"{v:g}"
    return str(v)


def lua(data):
    lines = ["-- Generated by tools/build_addon_zones.py (catalog/build_zone_guide.py): Classic estimates from CMaNGOS.",
             "-- q: {id, title, level, minLevel, side, xp, money, reward item, giver, x, y, type, classes, previous quest, {gear rewards}}",
             "-- s: {item, item name, quest, title, level, minLevel, side, dropped by, min, max, chance %, x, y}",
             "-- r: {name, min, max, rank, x, y, {{item, chance %}}}   m: {name, min, max, x, y, spawns, {{item, per kill}}}",
             "DufforthTweaksHelperZoneData = {"]
    for zone in sorted(data["zones"]):
        z = data["zones"][zone]
        lines.append(f"[{S(zone)}] = {{")
        for key, short in (("quests", "q"), ("starters", "s"), ("rares", "r"), ("mobs", "m")):
            lines.append(f"  {short} = {{" + ",".join(value(row) for row in z[key]) + "},")
        lines.append("},")
    lines.append("}")
    trainers = ROOT / "catalog" / "class_trainers.json"
    if trainers.exists():
        classes = json.loads(trainers.read_text(encoding="utf-8"))["classes"]
        lines.append("-- Class trainers: spells = {level, name, rank (0 = none), cost}, trainers = {name, side, zone, x, y}")
        lines.append("DufforthTweaksHelperClassTrainers = {")
        for cls in sorted(classes):
            c = classes[cls]
            lines.append(f"  {cls} = {{ spells = {value(c['spells'])}, trainers = {value(c['trainers'])} }},")
        lines.append("}")
    lines.append("-- {name, quality, vendor sell price}")
    lines.append("DufforthTweaksHelperZoneItems = {" + ",".join(f"[{i}]={value(v)}" for i, v in sorted(data["items"].items(), key=lambda kv: int(kv[0]))) + "}")
    return "\n".join(lines) + "\n"


def main(out):
    text = lua(load())
    Path(out).write_text(text, encoding="utf-8")
    print(f"{out}: {len(text) // 1024} KB")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
