#!/usr/bin/env python3
"""Enchanting material prices for the addon's disenchant tooltips.

    python tools/build_de_prices.py <price data folder> addon/DufforthAHScanner/DEPrices.lua

The addon prefers your own recent auction scan. These prices, from Blizzard's data at
download time, fill in when you haven't scanned.
"""
import json
import sys
from pathlib import Path

# Every dust, essence, shard and crystal the disenchant tables can give.
MATERIALS = [10940, 10938, 10939, 10998, 11082, 11134, 11135, 11174, 11175, 16202, 16203, 11083,
             11137, 11176, 16204, 10978, 11084, 11138, 11139, 11177, 11178, 14343, 14344, 20725]


def prices_for(items):
    """Market price (or lowest) for each material that is listed."""
    out = {}
    for material in MATERIALS:
        row = items.get(str(material))
        if row and row[2] and row[2] > 0:
            price = row[1] if row[1] is not None else row[0]
            if price:
                out[material] = int(price)
    return out


def lua(houses, stamp):
    lines = ["-- Generated by tools/build_de_prices.py. Enchanting material prices at download time.",
             f"DufforthAHScannerDEPrices = {{ at = {int(stamp)},"]
    for market in sorted(houses):
        prices = houses[market]
        if prices:
            body = ", ".join(f"[{k}] = {v}" for k, v in sorted(prices.items()))
            lines.append(f'  ["{market}"] = {{ {body} }},')
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(data, out):
    meta = json.loads((Path(data) / "meta.json").read_text(encoding="utf-8"))
    houses, stamp = {}, 0
    for house in meta["houses"]:
        path = Path(data) / f"h{house['id']}.json"
        if not path.exists():
            continue
        file = json.loads(path.read_text(encoding="utf-8"))
        houses[house["id"]] = prices_for(file.get("items", {}))
        stamp = max(stamp, file.get("ts") or 0)
    Path(out).write_text(lua(houses, stamp), encoding="utf-8")
    return houses


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    found = main(sys.argv[1], sys.argv[2])
    print(f"disenchant prices for {sum(1 for p in found.values() if p)} markets")
