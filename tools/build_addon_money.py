"""Writes the addon's Money tab data (MoneyData.lua): for every market, the best money ideas at the latest prices,
found by tools/money_finder.py (user, 2026-11-25: "Yes, add a Money tab").

    python tools/build_addon_money.py <state folder> <out.lua>

<state folder> holds meta.json and h<market>.json, like tools/build_addon_prices.py reads (the hourly job's `state`).
"""
import json
import sys
from pathlib import Path

import money_finder as M

TOP = 12


def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def ideas(items, cat, farm):
    flips = [(int(i), r["name"], int(r["lowest"]), int(r["vendor_pays"]), int(r["listed"]))
             for i, r in M.vendor_flips(items).head(TOP).iterrows()]
    cheap = [(int(i), r["name"], int(r["lowest"]), int(r["week"]), int(r["sold7"]))
             for i, r in M.underpriced(items).head(TOP).iterrows()]
    c = M.crafts(items, cat["recipes"])
    crafts = [(int(r["id"]), r["recipe"], r["profession"], int(r["skill"]), int(r["cost"]), int(r["sell"]), int(r["sold7"]))
              for _, r in c.head(TOP).iterrows()] if len(c) else []
    f = M.farming(items, farm)
    farming = [(r["monster"], r["level"], r["zone"], int(r["per_kill"]), int(r["per_hour"]), r["best_drop"])
               for _, r in f.head(TOP).iterrows()] if len(f) else []
    return {"flips": flips, "cheap": cheap, "crafts": crafts, "farm": farming}


def lua(markets, stamp):
    lines = ["-- Generated by tools/build_addon_money.py from the auction house prices. Do not edit.",
             "-- flips: { id, name, buy, vendor pays, listed }; cheap: { id, name, buy, usual (7-day), sold in 7 days };",
             "-- crafts: { product id, recipe, profession, skill, materials, sells (after the AH cut), sold in 7 days };",
             "-- farm: { monster, levels, zone, per kill, per hour, best drop } (copper).",
             f"DufforthTweaksHelperMoneyData = {{ at = {int(stamp)}, markets = {{"]
    for market in sorted(markets):
        m = markets[market]
        lines.append(f"  [{q(market)}] = {{")
        for key in ("flips", "cheap", "crafts", "farm"):
            rows = ", ".join("{ " + ", ".join(q(v) if isinstance(v, str) else str(v) for v in row) + " }" for row in m[key])
            lines.append(f"    {key} = {{ {rows} }},")
        lines.append("  },")
    lines.append("} }")
    return "\n".join(lines) + "\n"


def main(state, out):
    meta = json.loads((Path(state) / "meta.json").read_text(encoding="utf-8"))
    markets, stamp = {}, 0
    for house in meta["houses"]:
        path = Path(state) / f"h{house['id']}.json"
        if not path.exists():
            continue
        items, cat, farm = M.load(path)
        markets[house["id"]] = ideas(items, cat, farm)
        stamp = max(stamp, json.loads(path.read_text(encoding="utf-8")).get("ts") or 0)
    Path(out).write_text(lua(markets, stamp), encoding="utf-8")
    return markets


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    found = main(sys.argv[1], sys.argv[2])
    print(f"addon money ideas: {len(found)} markets")
