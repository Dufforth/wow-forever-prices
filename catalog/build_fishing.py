"""Build addon/DufforthTweaksHelper/FishingData.lua: the fish Codex (what bites where, and how often).

Run by hand, with the same CMaNGOS classic-db dump and Forever AreaTable as build_farm.py / build_grind.py:
    python catalog/build_fishing.py --cache <folder> --commit c33f90b8eeb3f8bacb53d5cbfee45075c80b416c

Fishing loot in the database is kept per area (a zone, or a lake or coast inside it). Each zone gets its own
catch list, and each named place inside it with a list of its own gets one too. Chances are per catch, in %.
Classic data: Forever may differ, so the addon also shows what you really caught there.
"""
import argparse
import gzip
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_farm  # noqa: E402
from build_farm import as_dicts, num  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "addon" / "DufforthTweaksHelper" / "FishingData.lua"
TABLES = ("fishing_loot_template", "reference_loot_template", "item_template")
MIN_CHANCE = 0.5   # % per catch: rarer ones are left out of the list
HAS_LOOT = 4       # item flag: it opens (fished-up chests, crates, clams)


def lua_str(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def build(tables, areas):
    fishing = build_farm.loot_index(as_dicts(tables["fishing_loot_template"]))
    reference = build_farm.loot_index(as_dicts(tables["reference_loot_template"]))
    items = {int(r["entry"]): r for r in as_dicts(tables["item_template"])}
    by_id = {int(num(a["ID"])): a for a in areas}
    zone_of = build_farm.area_zones(areas)
    zones, used = {}, set()
    for entry in sorted(fishing):
        if entry not in by_id or entry not in zone_of:
            continue
        got = build_farm.expected_items(entry, fishing, reference)
        rows = sorted(((item, round(chance * 100, 1)) for item, (chance, _) in got.items() if chance * 100 >= MIN_CHANCE and item in items),
                      key=lambda r: (-r[1], r[0]))
        if not rows:
            continue
        zone = zone_of[entry]
        place = by_id[entry]["AreaName_lang"]
        z = zones.setdefault(zone, {"loot": None, "subs": {}})
        if place == zone:
            z["loot"] = rows
        else:
            z["subs"][place] = rows
        used.update(item for item, _ in rows)
    # Places in one zone with the same list are shown once: "Sen'jin Village, Southfury River, ..."
    for z in zones.values():
        same = {}
        for place, rows in sorted(z["subs"].items()):
            if rows != z["loot"]:
                same.setdefault(tuple(rows), []).append(place)
        z["subs"] = {", ".join(places): list(rows) for rows, places in same.items()}
    names = {i: items[i]["name"] for i in sorted(used)}
    chests = sorted(i for i in used if int(num(items[i].get("Flags"))) & HAS_LOOT)
    return zones, names, chests


def write(zones, names, chests, commit):
    out = ["-- Generated by catalog/build_fishing.py from the CMaNGOS classic-db dump (commit " + commit[:10] + ").",
           "-- What bites where: per zone and named place, { item, % per catch }. Classic data: Forever may differ.",
           "DufforthTweaksHelperFishCodex = { zones = {"]
    for zone in sorted(zones):
        z = zones[zone]
        loot = ", ".join("{ %d, %s }" % (i, c) for i, c in (z["loot"] or []))
        subs = ", ".join("[%s] = { %s }" % (lua_str(p), ", ".join("{ %d, %s }" % (i, c) for i, c in rows))
                         for p, rows in sorted(z["subs"].items()))
        out.append("  [%s] = { loot = { %s }, subs = { %s } }," % (lua_str(zone), loot, subs))
    out.append("}, names = {")
    for i, n in names.items():
        out.append("  [%d] = %s," % (i, lua_str(n)))
    out.append("}, chests = { " + ", ".join("[%d] = true" % i for i in chests) + " } }")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--cache", type=Path, required=True, help="folder with the downloads (build_farm's cache)")
    parser.add_argument("--commit", required=True)
    parser.add_argument("--build", default="1.60.1.70862")
    args = parser.parse_args()
    raw = build_farm.fetch(f"https://raw.githubusercontent.com/{build_farm.DB_REPO}/{args.commit}/{build_farm.DB_FILE}",
                           args.cache / f"classicdb-{args.commit[:10]}.sql.gz", binary=True)
    tables = build_farm.read_dump(gzip.decompress(raw).decode("utf-8", "replace"), TABLES)
    import csv
    import io
    text = build_farm.fetch(f"{build_farm.WAGO}/db2/AreaTable/csv?build={args.build}", args.cache / f"AreaTable-{args.build}.csv")
    areas = list(csv.DictReader(io.StringIO(text)))
    zones, names, chests = build(tables, areas)
    write(zones, names, chests, args.commit)
    print(f"{len(zones)} zones, {sum(len(z['subs']) for z in zones.values())} places, {len(names)} items, {len(chests)} chests,"
          f" {OUT.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
