"""Builds the hunter pet guide's data (addon/DufforthTweaksHelper/PetData.lua) from the Classic database: every
tameable beast with its family, levels, attack speed, rank (elite, rare) and where it spawns, plus each family's
health, damage and armor modifiers (user, 2026-11-25: "pet guide for hunters: best pet, best skills, where to get
new pet skills in the open world, which pets are worth taming").

The database has no list of which beast teaches which skill rank, so the skills come from Pets.lua (Classic rank
levels) and the addon tells you to check a beast with Beast Lore before taming.

    python catalog/build_pets.py --cache <folder> [--commit <classic-db commit>]
"""
import argparse
import csv
import gzip
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "catalog"))
import build_farm  # noqa: E402
from build_route import make_where  # noqa: E402

OUT = ROOT / "addon" / "DufforthTweaksHelper" / "PetData.lua"
TAMEABLE = 1  # CreatureTypeFlags bit
# Family ids (CreatureFamily) of Classic hunter pets.
FAMILIES = {1: "Wolf", 2: "Cat", 3: "Spider", 4: "Bear", 5: "Boar", 6: "Crocolisk", 7: "Carrion Bird", 8: "Crab",
            9: "Gorilla", 11: "Raptor", 12: "Tallstrider", 20: "Scorpid", 21: "Turtle", 24: "Bat", 25: "Hyena",
            26: "Owl", 27: "Wind Serpent"}


def num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return 0.0


def family_stats(rows):
    """{family: (health, damage, armor)}. This database's pet_familystats has the damage and armor columns the other
    way round (cats come out with 1.10 armor and boars with 0.90 armor, the reverse of the game), so they're swapped."""
    out = {}
    for r in rows:
        fam = int(r["family"])
        if fam in FAMILIES:
            out[fam] = (round(num(r["healthModifier"]), 2), round(num(r["armorModifier"]), 2), round(num(r["damageModifier"]), 2))
    return out


def beasts(templates, spawns, where):
    """[(name, family, min level, max level, zone, x, y, attack ms, rank)] for tameable beasts, placed at the zone
    where most of their spawns are (first spawn in that zone)."""
    places = {}
    for s in spawns:
        places.setdefault(int(s["id"]), []).append((int(num(s["map"])), num(s["position_x"]), num(s["position_y"])))
    out = []
    for r in templates:
        fam = int(num(r["Family"]))
        if not int(num(r["CreatureTypeFlags"])) & TAMEABLE or fam not in FAMILIES:
            continue
        found = [w for w in (where(p) for p in places.get(int(r["Entry"]), []) if p[0] in (0, 1)) if w]
        if not found:
            continue
        zone = Counter(w[0] for w in found).most_common(1)[0][0]
        first = next(w for w in found if w[0] == zone)
        out.append((r["Name"], fam, int(num(r["MinLevel"])), int(num(r["MaxLevel"])), zone, round(first[1], 1),
                    round(first[2], 1), int(num(r["MeleeBaseAttackTime"])), int(num(r["Rank"]))))
    out.sort(key=lambda b: (b[1], b[2], b[0]))
    return out


def lua_text(families, stats, rows, commit):
    def q(s):
        return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'
    lines = ["-- Generated by catalog/build_pets.py from the Classic database (classic-db " + commit[:10] + "). Do not edit.",
             "DufforthTweaksHelperPetData = {",
             "  -- family id = { name, health, damage, armor }",
             "  families = {"]
    for fam in sorted(families):
        h, d, a = stats.get(fam, (1, 1, 1))
        lines.append(f"    [{fam}] = {{ {q(families[fam])}, {h}, {d}, {a} }},")
    lines += ["  },", "  -- { name, family, min level, max level, zone, x, y, attack ms, rank (1 elite, 2 rare elite, 4 rare) }",
              "  beasts = {"]
    for b in rows:
        lines.append(f"    {{ {q(b[0])}, {b[1]}, {b[2]}, {b[3]}, {q(b[4])}, {b[5]}, {b[6]}, {b[7]}, {b[8]} }},")
    lines += ["  },", "}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--cache", type=Path, required=True)
    parser.add_argument("--commit", default="c33f90b8eeb3f8bacb53d5cbfee45075c80b416c")
    args = parser.parse_args()
    raw = build_farm.fetch(f"https://raw.githubusercontent.com/{build_farm.DB_REPO}/{args.commit}/{build_farm.DB_FILE}",
                           args.cache / f"classicdb-{args.commit[:10]}.sql.gz", binary=True)
    tables = build_farm.read_dump(gzip.decompress(raw).decode("utf-8", errors="replace"), build_farm.TABLES + ("pet_familystats",))
    build_name = json.loads((ROOT / "site" / "catalog.json").read_text(encoding="utf-8"))["build"]

    def table(name):
        text = build_farm.fetch(f"{build_farm.WAGO}/db2/{name}/csv?build={build_name}", args.cache / f"{name}-{build_name}.csv")
        return list(csv.DictReader(text.splitlines()))
    wago = {name: table(name) for name in ("UiMapAssignment", "UiMap", "Map", "AreaTable")}
    where = make_where(wago, tables)
    stats = family_stats(build_farm.as_dicts(tables["pet_familystats"]))
    rows = beasts(build_farm.as_dicts(tables["creature_template"]), build_farm.as_dicts(tables["creature"]), where)
    OUT.write_text(lua_text(FAMILIES, stats, rows, args.commit), encoding="utf-8")
    print(f"{len(rows)} tameable beasts in {len(FAMILIES)} families -> {OUT.name}")


if __name__ == "__main__":
    main()
